"""
Crypto Centralized Risk, Target, & Sizing Authority — §4, §5, §10, §18
Enforces:
  1. No structural stop clamping (Reject invalid structure instead of forcing arbitrary tight stop).
  2. Realistic target generation based on market structure and envelope ceilings.
  3. Strict fractional position sizing for BTC/ETH spot & perpetuals.
  4. Independent Two-Clock lifecycles (Trigger TTL vs Active Holding Time Stop).
"""
from __future__ import annotations

import math
from decimal import Decimal
from typing import Literal, Optional
from pydantic import BaseModel, Field
import structlog

logger = structlog.get_logger()

CryptoDirection = Literal["LONG", "SHORT"]
CryptoTimeframe = Literal["1m", "3m", "5m", "15m", "1h", "1d"]


class CryptoStrategySetup(BaseModel):
    """Raw proposal generated by an individual crypto strategy algorithm."""
    strategy_name: str
    symbol: str = "BTCUSDT"
    direction: CryptoDirection
    timeframe: CryptoTimeframe = "1m"
    is_scalp: bool = True
    spot_price: Decimal
    entry_trigger: Decimal
    raw_structural_stop: Decimal
    structural_target_candidates: list[Decimal] = Field(default_factory=list)
    atr_val: Decimal = Decimal("100.0")
    confidence: float = 75.0


class CryptoValidatedRiskDecision(BaseModel):
    accepted: bool
    rejection_reason: Optional[str] = None
    config_version: int = 1

    # Final validated prices
    entry_price: Decimal
    stop_loss: Decimal
    target_1: Decimal
    target_2: Decimal

    # Risk / Reward metrics
    risk_points: float
    reward_t1_points: float
    reward_t2_points: float
    risk_reward_t1: float
    risk_reward_t2: float

    # Independent Lifecycles
    trigger_ttl_seconds: int
    active_time_stop_seconds: int
    runner_ttl_seconds: int = 300

    # Position Sizing
    quantity: float
    notional_usd: float
    max_usd_loss: float
    precision_decimals: int = 3


