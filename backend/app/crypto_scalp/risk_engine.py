class CryptoCentralRiskEngine:
    """
    Evaluates crypto setups against institutional risk envelopes.
    Guarantees 'No structural stop clamping' — invalid wide stops are rejected outright.
    """

    def __init__(self, envelopes: Optional[dict] = None):
        self._envelopes = envelopes or CRYPTO_RISK_ENVELOPES

    def evaluate(
        self,
        setup: CryptoStrategySetup,
        available_equity_usd: float = 10_000.0,
        risk_per_trade_pct: float = 1.0,  # 1% equity ($100 risk)
    ) -> CryptoValidatedRiskDecision:
        sym = setup.symbol.upper()
        clean_sym = "BTCUSDT" if "BTC" in sym else ("ETHUSDT" if "ETH" in sym else "BTCUSDT")
        desk_key = "1m_scalp" if setup.is_scalp or setup.timeframe in ("1m", "3m") else "5m_intraday"

        symbol_rules = self._envelopes.get(clean_sym, {}).get(desk_key)
        if not symbol_rules:
            return self._reject("CONFIG_MISSING", f"No envelope configured for {clean_sym} ({desk_key})", setup)

        # 1. Calculate Raw Structural Risk
        is_short = setup.direction == "SHORT"
        if not is_short:
            raw_risk = float(setup.entry_trigger - setup.raw_structural_stop)
        else:
            raw_risk = float(setup.raw_structural_stop - setup.entry_trigger)

        if raw_risk <= 0:
            return self._reject(
                "INVALID_STOP_ORIENTATION",
                "Stop loss must be placed defensively relative to entry trigger",
                setup,
            )

        # 2. Safety Invariant: Reject oversized stops without clamping
        max_allowed_risk = float(symbol_rules["max_risk_pts"])
        min_allowed_risk = float(symbol_rules["min_risk_pts"])

        if raw_risk > max_allowed_risk:
            return self._reject(
                "STRUCTURAL_RISK_EXCEEDS_ENVELOPE",
                f"Structural risk (${raw_risk:.2f}) exceeds maximum envelope ceiling (${max_allowed_risk:.2f})",
                setup,
            )

        # Volatility buffer check (ensure stop isn't inside micro noise)
        atr_risk = float(setup.atr_val) * float(symbol_rules.get("atr_multiplier", 1.0))
        validated_risk = max(raw_risk, min_allowed_risk, atr_risk)

        if validated_risk > max_allowed_risk:
            return self._reject(
                "VOLATILITY_RISK_EXCEEDS_ENVELOPE",
                f"ATR-adjusted risk (${validated_risk:.2f}) exceeds maximum allowable ceiling (${max_allowed_risk:.2f})",
                setup,
            )

        # Calculate finalized Stop Loss
        validated_risk_dec = Decimal(str(round(validated_risk, 4)))
        if not is_short:
            final_sl = setup.entry_trigger - validated_risk_dec
        else:
            final_sl = setup.entry_trigger + validated_risk_dec

        # 3. Target Engine (Realistic Excursion + Ceiling)
        t1_ceiling = float(symbol_rules["t1_ceiling_pts"])
        t2_ceiling = float(symbol_rules["t2_ceiling_pts"])
        min_rr = float(symbol_rules["min_rr"])

        candidate_t1_pts = None
        for cand in setup.structural_target_candidates:
            diff = float(abs(cand - setup.entry_trigger))
            if (validated_risk * min_rr) <= diff <= t1_ceiling:
                candidate_t1_pts = diff
                break

        if not candidate_t1_pts:
            candidate_t1_pts = min(validated_risk * 1.5, t1_ceiling)

        candidate_t2_pts = min(max(candidate_t1_pts * 1.6, validated_risk * 2.2), t2_ceiling)

        rr_t1 = round(candidate_t1_pts / validated_risk, 2)
        if rr_t1 < min_rr:
            return self._reject(
                "INSUFFICIENT_RR",
                f"Reward provides only {rr_t1}R (Minimum required: {min_rr}R)",
                setup,
            )

        t1_pts_dec = Decimal(str(round(candidate_t1_pts, 4)))
        t2_pts_dec = Decimal(str(round(candidate_t2_pts, 4)))
        if not is_short:
            final_t1 = setup.entry_trigger + t1_pts_dec
            final_t2 = setup.entry_trigger + t2_pts_dec
        else:
            final_t1 = setup.entry_trigger - t1_pts_dec
            final_t2 = setup.entry_trigger - t2_pts_dec

        # 4. Fractional Coin Position Sizing
        risk_budget_usd = available_equity_usd * (risk_per_trade_pct / 100.0)
        decimals = int(symbol_rules.get("precision_decimals", 3))

        raw_qty = risk_budget_usd / validated_risk if validated_risk > 0 else 0.0
        # Quantize to coin decimals
        quantized_qty = round(math.floor(raw_qty * (10 ** decimals)) / (10 ** decimals), decimals)

        if quantized_qty <= 0:
            return self._reject(
                "INSUFFICIENT_CAPITAL_FOR_MIN_QUANTITY",
                f"Risk budget ${risk_budget_usd:.1f} cannot absorb minimum quantity at ${validated_risk:.2f} risk/unit",
                setup,
            )

        spot_f = float(setup.entry_trigger)
        notional_usd = round(quantized_qty * spot_f, 2)
        max_usd_loss = round(quantized_qty * validated_risk, 2)

        return CryptoValidatedRiskDecision(
            accepted=True,
            entry_price=setup.entry_trigger,
            stop_loss=final_sl,
            target_1=final_t1,
            target_2=final_t2,
            risk_points=round(validated_risk, 2),
            reward_t1_points=round(candidate_t1_pts, 2),
            reward_t2_points=round(candidate_t2_pts, 2),
            risk_reward_t1=rr_t1,
            risk_reward_t2=round(candidate_t2_pts / validated_risk, 2),
            trigger_ttl_seconds=int(symbol_rules["trigger_ttl_seconds"]),
            active_time_stop_seconds=int(symbol_rules["active_time_stop_seconds"]),
            runner_ttl_seconds=int(symbol_rules.get("runner_ttl_seconds", 300)),
            quantity=quantized_qty,
            notional_usd=notional_usd,
            max_usd_loss=max_usd_loss,
            precision_decimals=decimals,
        )

    def _reject(self, reason_code: str, message: str, setup: CryptoStrategySetup) -> CryptoValidatedRiskDecision:
        logger.info(
            "crypto_risk_decision_rejected",
            strategy=setup.strategy_name,
            symbol=setup.symbol,
            reason=reason_code,
            message=message,
        )
        return CryptoValidatedRiskDecision(
            accepted=False,
            rejection_reason=f"{reason_code}: {message}",
            entry_price=setup.entry_trigger,
            stop_loss=setup.raw_structural_stop,
            target_1=Decimal("0"),
            target_2=Decimal("0"),
            risk_points=0.0,
            reward_t1_points=0.0,
            reward_t2_points=0.0,
            risk_reward_t1=0.0,
            risk_reward_t2=0.0,
            trigger_ttl_seconds=0,
            active_time_stop_seconds=0,
            quantity=0.0,
            notional_usd=0.0,
            max_usd_loss=0.0,
        )


